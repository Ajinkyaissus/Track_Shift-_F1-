headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'}

print(f"Starting driver headshot asset downloads to {OUTPUT_DIR}...")
for slug, url in DRIVER_HEADSHOT_URLS.items():
    out_file = os.path.join(OUTPUT_DIR, f"{slug}.webp")
    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=10) as resp:
            img_data = resp.read()
            img = Image.open(io.BytesIO(img_data)).convert("RGBA")
            # Resize and save as optimized WebP
            img.thumbnail((320, 320), Image.Resampling.LANCZOS)
            img.save(out_file, "WEBP", quality=90)
            print(f"  [OK] {slug}.webp ({img.size[0]}x{img.size[1]})")
    except Exception as e:
        print(f"  [Error] {slug}: {e}")

print("Driver headshot asset generation complete.")
