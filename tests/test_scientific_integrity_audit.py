def test_tcn_checkpoint_manifest_and_weights_integrity():
    """Verify that TCN checkpoint exists, is trained, and matches SHA-256 manifest."""
    assert os.path.exists(MODEL_DIR), f"TCN directory {MODEL_DIR} not found"
    
    manifest_path = os.path.join(MODEL_DIR, "manifest.json")
    model_path = os.path.join(MODEL_DIR, "model.pt")
    metrics_path = os.path.join(MODEL_DIR, "metrics.json")
    config_path = os.path.join(MODEL_DIR, "config.json")
    
    assert os.path.exists(manifest_path)
    assert os.path.exists(model_path)
    assert os.path.exists(metrics_path)
    assert os.path.exists(config_path)

    # Check metrics
    with open(metrics_path, "r") as f:
        metrics = json.load(f)
    assert "held_out_test_rmse" in metrics
    assert "best_val_loss" in metrics
    assert metrics["best_val_loss"] > 0.0

    # Load weights
    state_dict = torch.load(model_path, map_location="cpu", weights_only=False)
    assert len(state_dict) > 0

    # Prove weights are non-trivial and not all zeros or unit constants
    for k, v in state_dict.items():
        if hasattr(v, "float") and v.numel() > 1:
            std = float(v.float().std())
            assert std > 1e-6, f"Weight tensor {k} has zero variance (uninitialized)"


def test_tcn_trained_vs_random_initialization_proof():
    """
    Prove that trained_model != random_initialization.
    Embeddings generated by the trained checkpoint must differ systematically
    from an uninitialized random network.
    """
    wrapper = BehavioralModelWrapper(architecture="tcn")
    assert wrapper.is_trained, "BehavioralModelWrapper must report is_trained=True"

    # Create uninitialized random model
    random_model = TemporalBehavioralTCN(in_features=5, embedding_dim=DEFAULT_EMBEDDING_DIM)
    random_model.eval()

    # Sample realistic telemetry sequence (5 features, 20 laps)
    sample_seq = np.array([
        [50.0 + np.sin(i) * 5.0, 3.0 + np.cos(i) * 0.5, 0.4 + np.sin(i) * 0.1, 140.0 + np.cos(i) * 10.0, 0.01]
        for i in range(20)
    ], dtype=np.float32)

    trained_emb = wrapper.generate_embedding(sample_seq)
    
    # Random model inference
    with torch.no_grad():
        x_tensor = torch.from_numpy(sample_seq.T[np.newaxis, :, :]).float()
        random_emb = random_model(x_tensor).squeeze(0).numpy()

    # Compare embeddings
    l2_dist = float(np.linalg.norm(trained_emb - random_emb))
    assert l2_dist > 0.1, f"Trained embedding is indistinguishable from random initialization (dist={l2_dist})"


def test_tcn_feature_sensitivity():
    """
    Prove that changing real telemetry inputs systematically modifies the resulting embedding.
    """
    wrapper = BehavioralModelWrapper(architecture="tcn")
    
    base_seq = np.array([
        [45.0, 2.8, 0.35, 120.0, 0.0] for _ in range(15)
    ], dtype=np.float32)

    # Modified sequence with higher braking aggression and throttle transients
    modified_seq = np.array([
        [65.0, 4.5, 0.55, 160.0, 0.05] for _ in range(15)
    ], dtype=np.float32)

    emb_base = wrapper.generate_embedding(base_seq)
    emb_mod = wrapper.generate_embedding(modified_seq)

    dist = float(np.linalg.norm(emb_base - emb_mod))
    assert dist > 0.05, f"TCN embedding insensitive to telemetry changes (dist={dist})"


